let gameLanguage = localStorage.getItem('starship-language') || 'fr';
function t(key) {
    if (gameLanguage === 'fr') return key;
    return (TRANSLATIONS.en && TRANSLATIONS.en[key]) || key;
}
function tf(key, vars) {
    let str = t(key);
    for (const v in (vars || {})) {
        str = str.split('{' + v + '}').join(vars[v]);
    }
    return str;
}
function setGameLanguage(lang) {
    gameLanguage = lang;
    localStorage.setItem('starship-language', lang);
    document.documentElement.lang = lang;
    applyStaticTranslations();
    updateLanguageButtons();
    if (document.getElementById('stats-modal').classList.contains('active')) renderStats();
    renderUpgrades();
    renderBuildings();
    renderGalacticShop();
    renderRocketPartsShop();
    updateSpaceProgress();
    updateAllBuildingButtons();
}
function updateLanguageButtons() {
    const fr = document.getElementById('lang-fr');
    const en = document.getElementById('lang-en');
    if (fr) fr.classList.toggle('active', gameLanguage === 'fr');
    if (en) en.classList.toggle('active', gameLanguage === 'en');
}
function applyStaticTranslations() {
    document.querySelectorAll('[data-i18n-booster]').forEach(el => {
        el.textContent = t(el.textContent);
    });
    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
}
function initLanguage() {
    document.documentElement.lang = gameLanguage;
    applyStaticTranslations();
    updateLanguageButtons();
}
